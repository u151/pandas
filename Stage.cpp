void Stage::Draw()
{
	// ステージの描画
	for (int y = 0; y < STAGE_HEIGHT; y++)
	{
		for (int x = 0; x < STAGE_WIDTH; x++)
		{
		int x1 = x * CHA_SIZE;
			int y1 = y * CHA_SIZE;
			int x2 = (x + 1) * CHA_SIZE;
			int y2 = (y + 1) * CHA_SIZE;
			DrawBox(x * CHA_SIZE, y * CHA_SIZE, (x + 1) * CHA_SIZE, (y + 1) * CHA_SIZE, GetColor(230, 200, 200), FALSE, 1);
			if (stageData[y][x] == 1)
			{
				DrawBox(x * CHA_SIZE, y * CHA_SIZE, (x + 1) * CHA_SIZE, (y + 1) * CHA_SIZE, GetColor(182,82,51), TRUE);
			}
		}
	}
}

